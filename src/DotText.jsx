export function DotText({ text, pitchX = 5, radius = 1.55, className = 'dot-svg' }) {
  const { circles, width } = useMemo(() => {
    const out = [];
    let x = 0;
    for (const ch of String(text)) {
      const g = GLYPHS[ch];
      if (!g) { x += 3 * pitchX; continue; }
      const cols = g[0].length;
      g.forEach((row, y) => [...row].forEach((bit, col) => {
        if (bit === '1') out.push([x + col * pitchX + 1.55, y * 4 + 1.55]);
      }));
      x += (cols + 1) * pitchX;
    }
    return { circles: out, width: x };
  }, [text, pitchX]);
  return (
    <svg className={className} viewBox={`0 0 ${width} 28`} fill="currentColor" aria-hidden="true" style={{ '--vbw': width }}>
      {circles.map(([cx, cy], i) => <circle key={i} cx={cx} cy={cy} r={radius} />)}
    </svg>
  );
}

// One accent word inside a heading, drawn in LED dots. Screen readers get the plain word.
// `lead` drops the left margin when the word starts a line.
export function DotWord({ text, lead = false }) {
  return (
    <span className={`dot-word${lead ? ' dot-word--lead' : ''}`}>
      <DotText text={text} pitchX={4} radius={1.8} />
      <span className="sr-only">{text}</span>
    </span>
  );
}
